#!/usr/bin/env python3
"""
Build golden selects_candidates.yaml from:
  1) Human edit data (FCP CoreData decode) — which takes were used, in/out, timeline order
  2) 03_analysis/segments.json — segment_id, asset_id, src ranges (generated by analyze pipeline)

Maps human selections onto analysis segments via filename matching + temporal overlap.
"""
import json, yaml, re, sys
from pathlib import Path

PROJ = Path("/Users/mocchalera/Dev/video-os-v2-spec/projects/togakushi-camp")
SEGMENTS_PATH = PROJ / "03_analysis" / "segments.json"
ASSETS_PATH = PROJ / "03_analysis" / "assets.json"
OUTPUT_PATH = PROJ / "04_plan" / "selects_candidates.yaml"

# === Human edit data (from decode2.py / decode_order.py output) ===
# Timeline-ordered cuts with source durations
# Format: (take_name, play_dur_s, src_dur_s, position_in_timeline)
HUMAN_CUTS = [
    ("T015", 3.88, 7.09, 1),
    ("T012", 2.46, 12.60, 2),
    ("T016", 2.83, 9.13, 3),
    ("T020", 2.83, 11.09, 4),
    ("T018", 3.83, 10.64, 5),
    ("T023", 3.83, 8.05, 6),
    ("T026", 3.50, 16.64, 7),
    ("T029", 4.71, 5.19, 8),
    ("T031", 5.75, 12.16, 9),
    ("T035", 3.67, 16.06, 10),
    ("T036", 2.71, 11.55, 11),
    ("T039", 2.79, 10.09, 12),
    ("T042", 2.92, 7.09, 13),
    ("T037", 3.21, 17.10, 14),
    ("T050", 5.92, 12.60, 15),
    ("T056", 8.75, 12.75, 16),
    ("T058", 4.25, 13.31, 17),
    ("T062", 4.92, 10.73, 18),
    ("T001", 4.29, 17.60, 19),
    ("T005", 4.42, 15.57, 20),
    ("T003", 4.58, 11.88, 21),
    ("T008", 3.71, 49.13, 22),
    ("T009", 4.54, 21.06, 23),
    ("T010", 4.46, 18.14, 24),
    ("T012", 3.92, 18.06, 25),  # reuse
    ("T015", 3.50, 7.09, 26),   # reuse
    ("T016", 4.46, 10.09, 27),  # reuse
    ("T019", 3.08, 7.09, 28),
    ("T027", 4.00, 6.79, 29),
]

# Unique takes used by human
HUMAN_TAKES = sorted(set(t for t, *_ in HUMAN_CUTS))

def main():
    if not SEGMENTS_PATH.exists():
        print(f"ERROR: {SEGMENTS_PATH} not found. Run batch_analyze.sh first.")
        sys.exit(1)

    segments = json.loads(SEGMENTS_PATH.read_text())["items"]
    assets = json.loads(ASSETS_PATH.read_text())["items"]

    # Build asset display_name -> asset_id map
    name_to_asset = {}
    for a in assets:
        dn = a.get("display_name", "")
        name_to_asset[dn] = a["asset_id"]

    # Build asset_id -> segments map
    asset_segments = {}
    for s in segments:
        aid = s["asset_id"]
        asset_segments.setdefault(aid, []).append(s)

    print(f"Loaded: {len(assets)} assets, {len(segments)} segments")
    print(f"Human used {len(HUMAN_TAKES)} unique takes ({len(HUMAN_CUTS)} placements)")

    # Map each human take to its asset_id
    candidates = []
    missing = []
    seen_segments = set()

    for take in HUMAN_TAKES:
        full_name = f"NINJAV_S001_S001_{take}"
        asset_id = name_to_asset.get(full_name)
        if not asset_id:
            missing.append(take)
            continue

        segs = asset_segments.get(asset_id, [])
        if not segs:
            missing.append(take)
            continue

        # How many times this take appears in timeline
        appearances = [(pos, pd, sd) for t, pd, sd, pos in HUMAN_CUTS if t == take]

        # For each segment of this asset, check if it was used
        for seg in segs:
            seg_id = seg["segment_id"]
            if seg_id in seen_segments:
                continue
            seen_segments.add(seg_id)

            # Determine role based on timeline position
            positions = [pos for pos, _, _ in appearances]
            is_opening = any(p <= 3 for p in positions)
            is_closing = any(p >= 25 for p in positions)
            is_reused = len(appearances) > 1

            if is_opening and is_reused:
                role = "hero"
                why = f"Opening shot of Togakushi landscape, reused as bookend (positions {positions})"
            elif is_opening:
                role = "hero"
                why = f"Opening sequence establishing Togakushi setting (position {positions[0]})"
            elif is_closing:
                role = "support"
                why = f"Closing sequence of 2-day camp journey (position {positions[0]})"
            elif any(p <= 14 for p in positions):
                role = "support"
                why = f"Day 1 activity/atmosphere (position {positions[0]})"
            else:
                role = "texture"
                why = f"Day 2 morning/activity (position {positions[0]})"

            candidate = {
                "segment_id": seg_id,
                "asset_id": asset_id,
                "src_in_us": seg["src_in_us"],
                "src_out_us": seg["src_out_us"],
                "role": role,
                "why_it_matches": why,
                "risks": [],
                "confidence": 0.95,
                "semantic_rank": min(positions),
            }
            candidates.append(candidate)

    if missing:
        print(f"WARNING: {len(missing)} takes not found in analysis: {missing}")
        print("  (These clips may not have been analyzed yet)")

    print(f"Generated {len(candidates)} candidates")

    # Write selects
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    selects = {
        "version": "1",
        "project_id": "togakushi-camp",
        "created_at": "2026-06-15T23:00:00Z",
        "analysis_artifact_version": "analysis-v1",
        "selection_notes": [
            "Human golden reconstructed from FCP CoreData (2021-10-29 edit)",
            f"{len(HUMAN_TAKES)} unique takes selected from 300-clip NINJAV pool (8.7% selection rate)",
            "2-day camp structure: Day 1 (#1-14) → Day 2 (#15-29)",
            "T015/T012/T016 reused as opening+closing bookend (Togakushi landscape)",
            "9 clips with retiming (slow motion), 32 with color grading",
            "Music: Only This Matters (Adobe Stock) full-length background",
        ],
        "candidates": candidates,
    }

    with open(OUTPUT_PATH, "w") as f:
        yaml.dump(selects, f, allow_unicode=True, default_flow_style=False, sort_keys=False)

    print(f"Written to {OUTPUT_PATH}")

if __name__ == "__main__":
    main()
